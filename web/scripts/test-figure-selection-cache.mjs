import assert from "node:assert/strict";
import { FigureSelectionStore } from "../lib/figure-selection.ts";

let now = 1000;
const options = { maxBytes: 2000, maxContexts: 2, ttlMs: 100, now: () => now };
const store = new FigureSelectionStore(options);
const release = { release_id: "release-a", source_hash: "source-a" };
const record = { record_id: "rec_a", values: { tensile_strength: 2 } };
const first = store.create([record], release);
assert.match(first.token, /^[A-Za-z0-9_-]{43}$/);
assert.equal(store.read(first.token, "rec_absent"), "not_plotted");
assert.equal(store.read("forged", "rec_a"), "expired");
record.values.tensile_strength = 999;
release.release_id = "changed";
const selected = store.read(first.token, "rec_a");
assert.equal(selected.record.values.tensile_strength, 2);
assert.equal(selected.release.release_id, "release-a");
selected.record.values.tensile_strength = 777;
assert.equal(store.read(first.token, "rec_a").record.values.tensile_strength, 2);
const second = store.create([record], release);
store.read(first.token, "rec_a");
const third = store.create([record], release);
assert.equal(store.read(second.token, "rec_a"), "expired", "Least-recently-used context should be evicted");
assert.equal(store.read(first.token, "rec_a").record.record_id, "rec_a");
now = 1100;
assert.equal(store.read(first.token, "rec_a"), "expired");
assert.equal(store.read(third.token, "rec_a"), "expired");
const small = new FigureSelectionStore({ ...options, maxBytes: 100 });
const a = small.create([record], release);
const b = small.create([record], release);
assert.equal(small.read(a.token, "rec_a"), "expired", "Byte budget should evict a context");
assert.equal(small.read(b.token, "rec_a").record.record_id, "rec_a");
assert.throws(() => small.create([{ record_id: "big", note: "a".repeat(200) }], release), /memory budget/);
console.log("Selection cache passed: membership, unguessable tokens, immutable release/values, expiry, LRU and byte budget.");
